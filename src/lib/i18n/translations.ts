export type TranslationKey = keyof typeof translations.en;
export type TranslationDictionary = Record<TranslationKey, string>;

export function translate(
  language: SupportedLanguage,
  key: TranslationKey,
  values: Record<string, string | number> = {},
) {
  let value =
    (translations[language] as TranslationDictionary)[key] ?? translations.en[key];
  for (const [name, replacement] of Object.entries(values)) {
    value = value.replace(`{${name}}`, String(replacement));
  }
  return value;
}

export function localizedValue<T extends Record<string, unknown>>(
  value: T,
  field: string,
  language: SupportedLanguage,
  fallback: SupportedLanguage = "en",
) {
  return (
    (value[`${field}_${language}`] as string | null | undefined) ??
    (value[`${field}_${fallback}`] as string | null | undefined) ??
    ""
  );
}
